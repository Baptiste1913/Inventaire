'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const transport=require('../gemini-transport.js');
const lab=fs.readFileSync('gemini-lab.js','utf8'),parallel=fs.readFileSync('gemini-parallel.js','utf8');
(async()=>{
 const bytes=new Uint8Array(120000).fill(71);bytes[0]=255;bytes[1]=216;
 const original=new Blob([bytes],{type:'image/jpeg'});
 const detail=new Blob([bytes.slice(0,40000)],{type:'image/jpeg'});
 transport.observe({transport:'binary-v1'});
 const a=transport.wrapJPEG(original),b=transport.wrapJPEG(detail);
 const packet=await transport.prepareAsync({model:'gemini-3.5-flash-lite',imageBase64:a,detailImageBase64:b});
 const data=new Uint8Array(await packet.body.arrayBuffer()),n=new DataView(data.buffer).getUint32(0);
 assert.equal(packet.contentType,'application/octet-stream');
 assert.deepEqual(data.slice(4+n,4+n+original.size),bytes);
 assert.deepEqual(data.slice(4+n+original.size),bytes.slice(0,40000));
 let reads=0;global.FileReader=class{readAsDataURL(blob){reads++;blob.arrayBuffer().then(buffer=>{this.result='data:image/jpeg;base64,'+Buffer.from(buffer).toString('base64');this.onload();});}};
 transport.reset();
 const json=JSON.parse((await transport.prepareAsync({imageBase64:a,detailImageBase64:b})).body);
 assert.equal(json.imageBase64,Buffer.from(bytes).toString('base64'));
 await transport.prepareAsync({imageBase64:a,detailImageBase64:b});assert.equal(reads,2);
 delete global.FileReader;
 const instances=[],messages=[];
 class Worker{constructor(url){this.url=url;instances.push(this);}postMessage(msg){messages.push([this.url,msg.kind]);Promise.resolve().then(()=>this.onmessage?.({data:{id:msg.id,result:msg.kind==='barcode'?{confirmed:true,ean13:'0203476013844'}:{size:1234}}}));}terminate(){this.closed=true;}}
 const window={Worker,OffscreenCanvas:class{},createImageBitmap(){},navigator:{hardwareConcurrency:6}};
 vm.runInNewContext(parallel,{window,setTimeout,clearTimeout});
 const api=window.IUGeminiParallel;
 api.preloadBarcode();api.warmDetail();api.warmExtra();
 await Promise.all([api.barcode(original),api.prepareDetail(original),api.prepareFocused(original,null,122000,'ean'),api.partial(original),api.digits(original,null)]);
 assert.equal(instances.length,4);assert(messages.some(x=>x[1]==='digit-template'));
 api.close();assert(instances.every(x=>x.closed));
 assert(messages.some(x=>x[1]==='warm-recovery'));
 assert(lab.includes('requestTimings:[{packetMs,headersMs,parseMs'));
 assert(lab.includes('parallelCapacity?.()'));
 assert(lab.includes('partialJob=earlyPartialJob||track('));
 assert(!lab.slice(lab.indexOf('const earlyTimer='),lab.indexOf('void opticalTask.promise.then(()=>clearTimeout(earlyTimer))')).includes('digitJob=track('));
 assert(lab.includes('const qualityRing=[]')&&lab.includes('qualityRing.length>qualityRingLimit'));
 assert(lab.includes('const localDeadline=performance.now()+350')&&lab.includes('const finalDeadline=performance.now()+110'));
 assert(lab.includes('const fixedModel=\'gemini-3.5-flash-lite\''));
 assert(lab.includes('validated.timing={preparationMs,firstResponseMs,recoveryMs'));
 console.log('OK : transport sans perte, négociation JSON, quatre Workers bornés, validation inchangée.');
})().catch(e=>{console.error(e);process.exitCode=1;});
